import { AppLanguage, LANGUAGES } from '../types/i18n';

const STORAGE_KEY = 'arunan_iq_language';

export function getInitialLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as AppLanguage;
    if (saved && LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
    const navLang = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : '').toLowerCase();
    if (navLang.startsWith('en')) return 'en';
    if (navLang.startsWith('ta')) return 'ta';
    if (navLang.startsWith('fr')) return 'fr';
    if (navLang.startsWith('es')) return 'es';
    if (navLang.startsWith('hi')) return 'hi';
  } catch {}
  return 'en'; // default main language is English
}

export function saveLanguage(lang: AppLanguage) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {}
}

